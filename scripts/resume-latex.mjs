#!/usr/bin/env node
// Generates resume-pdf/main.tex from app/resume/source.ts (the single source of truth)
// and resume-pdf/template.tex (the hand-edited LaTeX layout).
//
//   npm run resume:tex          # write resume-pdf/main.tex
//   npm run resume:tex -- --pdf # also compile resume-pdf/main.pdf (needs pdflatex)
//   npm run resume:tex -- --check  # exit 1 if main.tex is stale (for CI / pre-commit)
//
// Upload main.tex + style.cls to Overleaf (or sync via Overleaf's Git/GitHub integration).

import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { resume as source } from '../app/resume/source.ts'
import { resolve, resolveAll } from '../app/resume/variants.ts'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dir = join(root, 'resume-pdf')
const args = new Set(process.argv.slice(2))

// ---------- text → LaTeX ----------

const PLACEHOLDER = (i) => `\u0000${i}\u0000`

/** Escapes plain text for LaTeX and applies typographic substitutions. */
function tex(text) {
  return text
    .replace(/\\/g, '\u0001')
    .replace(/([&%$#_{}])/g, '\\$1')
    .replace(/\u0001/g, '\\textbackslash{}')
    .replace(/[~∼]/g, '$\\sim$')
    .replace(/×/g, '$\\times$')
    .replace(/\^/g, '\\textasciicircum{}')
    .replace(/“/g, '``')
    .replace(/”/g, "''")
    .replace(/[‘’]/g, "'")
    .replace(/ – /g, ' - ')
    .replace(/–/g, '--')
    .replace(/—/g, '---')
    .replace(/C\+\+/g, '\\CC{}')
    .replace(/\bLaTeX\b/g, '\\LaTeX{}')
}

/**
 * Converts a content string to LaTeX: escapes it, turns `links` labels into \href,
 * and (PDF-only markup) **bold** / *italic*.
 */
function rich(text, links = []) {
  const stash = []
  let out = text
  for (const link of links) {
    out = out.split(link.label).join(PLACEHOLDER(stash.length))
    stash.push(`\\href{${link.href.replace(/([%#])/g, '\\$1')}}{${tex(link.label)}}`)
  }
  out = tex(out)
    .replace(/\*\*(.+?)\*\*/g, '\\textbf{$1}')
    .replace(/\*(.+?)\*/g, '{\\it $1}')
  return out.replace(/\u0000(\d+)\u0000/g, (_, i) => stash[Number(i)])
}

// ---------- sections ----------

const top = resolve(source, 'pdf')
const experience = resolveAll(source.experience, 'pdf').map((job) => ({
  ...job,
  bullets: resolveAll(job.bullets, 'pdf'),
}))
const education = resolveAll(source.education, 'pdf')
const skills = resolveAll(source.skills, 'pdf')
const { contact } = top

const header = `\\begin{tabular*}{\\textwidth}{@{}l@{\\extracolsep{\\fill}}l@{}}
\\textbf{\\Large ${tex(top.name.toUpperCase())}} & Email: \\href{mailto:${contact.email}}{${tex(contact.email)}}\\\\
Blog: \\href{${contact.blogUrl}}{${tex(contact.blog)}} & Phone: ${tex(contact.phone)}\\\\
\\end{tabular*}`

const list = (items) => `\\begin{list2}\n${items.map((i) => `\\item \\rm ${i}`).join('\n')}\n\\end{list2}`

const entries = (blocks) => blocks.join('\n\n\\vspace{-0.5em}\n')

const body = [
  `\\section{\\sc Summary}\n\n${rich(top.summary)}`,

  `\\section{\\sc Experience}\n\n` +
    entries(
      experience.map(
        (job) =>
          `{\\bf ${tex(job.company)}}, {\\it ${tex(job.role)}} \\hfill {\\it ${tex(job.dates)}}\\\\\n` +
          list(
            job.bullets.map((b) =>
              b.lead
                ? `\\textbf{${rich(b.lead, b.links)}:} ${rich(b.text, b.links)}`
                : rich(b.text, b.links)
            )
          )
      )
    ),

  `\\section{\\sc Education}\n\n` +
    entries(
      education.map(
        (edu) =>
          `{\\bf ${tex(edu.school)}} \\hfill {\\it ${tex(edu.dates)}}\\\\\n` + list(edu.details.map((d) => rich(d)))
      )
    ),

  `\\section{\\sc Expertise}\n\n` +
    skills.map((s) => `\\rm \\textbf{${tex(s.label)}:} ${s.items.map((i) => rich(i)).join(', ')}`).join('\\\\\n'),
].join('\n\n')

// ---------- output ----------

const banner = '% GENERATED by scripts/resume-latex.mjs from app/resume/source.ts. Do not edit by hand.\n'
const template = readFileSync(join(dir, 'template.tex'), 'utf8')
const output =
  banner +
  template
    .replace(/^%.*\n%.*\n\n/, '') // drop the template's own "hand-edited layout" comment
    .replace('%%HEADER%%', () => header)
    .replace('%%BODY%%', () => body)

const target = join(dir, 'main.tex')

if (args.has('--check')) {
  const current = readFileSync(target, 'utf8')
  if (current !== output) {
    console.error('resume-pdf/main.tex is stale. Run `npm run resume:tex` and commit the result.')
    process.exit(1)
  }
  console.log('resume-pdf/main.tex is up to date.')
  process.exit(0)
}

writeFileSync(target, output)
console.log('Wrote resume-pdf/main.tex')

if (args.has('--pdf')) {
  execFileSync('latexmk', ['-pdf', '-interaction=nonstopmode', '-halt-on-error', 'main.tex'], {
    cwd: dir,
    stdio: 'inherit',
  })
  execFileSync('latexmk', ['-c'], { cwd: dir, stdio: 'ignore' })
  console.log('Wrote resume-pdf/main.pdf')
}
